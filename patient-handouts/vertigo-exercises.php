          <p>Patients with neurological (nerve/nervous system) injuries or disorders are often asked to do neuro rehabilitation exercises. Those who have had a stroke, sustained a brain injury, or are recovering from a vestibular (inner-ear balance) problem may benefit from this regimen. Below are general exercises commonly used to help with vertigo. The descriptions are standard guidance and are not a substitute for a personal evaluation by your doctor.</p>
          <p>Perform the movements slowly and in a safe environment. Sit or lie down if you feel unsteady, and keep a firm support within reach.</p>

          <h2>Exercises in Bed (Seated or Lying)</h2>
          <ul class="exercise-grid">
            <li class="exercise-item">
              <img src="../images/ex-vertigo-look-up-down.jpg" alt="Looking up and then down exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Looking up and then down</h3>
                <p>While seated or lying down, slowly tilt your head as far up as is comfortable, hold for a few seconds, then return to centre. Slowly tilt your head down toward your chest, hold, and return to centre. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-look-left-right.jpg" alt="Looking left and right alternately exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Looking left and right alternately</h3>
                <p>Keep your head still and slowly move your eyes as far to the right as possible, hold, then move them as far to the left as possible and hold. Return to centre. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-convergence.jpg" alt="Convergence exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Convergence exercises</h3>
                <p>Hold a small object (such as a pen) at arm's length in front of your face. Slowly bring it toward the tip of your nose while keeping the object in focus, then slowly move it back out. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-shoulder.jpg" alt="Shrugging and rotating shoulders exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Shrugging and rotating shoulders</h3>
                <p>Lift your shoulders up toward your ears, hold briefly, then relax. Roll your shoulders backward in a slow circle, then forward. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-bend-pick.jpg" alt="Bending forward and picking up objects exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Bending forward and picking up objects</h3>
                <p>From a seated position, slowly bend forward as if reaching for an object on the floor, then return to an upright position. You can place a real object in front of you to pick up. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-turn-head-trunk.jpg" alt="Turning head and trunk to left and right alternately exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Turning head and trunk to left and right alternately</h3>
                <p>Sit upright and slowly turn your head and upper body to look over one shoulder, hold briefly, return to centre, then repeat on the other side. Move only as far as is comfortable.</p>
              </div>
            </li>
          </ul>

          <h2>Head Movements (Sitting or Standing)</h2>
          <ul class="exercise-grid">
            <li class="exercise-item">
              <img src="../images/ex-vertigo-bend-fwd-back.jpg" alt="Bending forward and backwards alternately exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Bending forward and backwards alternately</h3>
                <p>Sit or stand with good posture. Slowly bend your head and upper body forward, then return upright. Slowly lean your head and upper body backward (only as far as is comfortable), then return upright. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-vertigo-turn-left-right.jpg" alt="Turning left and then right alternately exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Turning left and then right alternately</h3>
                <p>Keep your shoulders still and slowly turn your head to look over one shoulder, hold briefly, then turn to look over the other shoulder. Repeat several times.</p>
              </div>
            </li>
          </ul>

          <div class="callout-tip">
            <strong>Tip:</strong> Move slowly and breathe normally throughout each exercise. Start with a small number of repetitions and only increase as your tolerance improves. Many people find it helpful to do a short session two to three times a day rather than one long session.
          </div>

          <div class="callout-warning">
            <strong>When to see a doctor:</strong> Stop the exercises and seek medical advice if you experience sudden hearing loss, double vision, slurred speech, weakness or numbness in the arms or legs, a severe or unusual headache, fainting, repeated vomiting, or a fall. If your vertigo is new, worsening, or different from prior episodes, get evaluated before continuing home exercises.
