          <p>Patients with neurological (nerve/nervous system) injuries or disorders are often asked to do neuro rehabilitation exercises. Strengthening the muscles that support the spine can help with posture, reduce strain on the lower back, and improve day-to-day function. The exercises below are standard, widely used movements for general back conditioning. The descriptions are general guidance and are not a substitute for a personal evaluation by your doctor or physiotherapist.</p>
          <p>Begin with a small number of repetitions, move within a pain-free range, and breathe normally throughout each exercise.</p>

          <h2>Stretches</h2>
          <ul class="exercise-grid">
            <li class="exercise-item">
              <img src="../images/ex-back-hamstring-stretch.jpg" alt="Hamstring stretch exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Standard hamstring stretch</h3>
                <p>Lie on your back with both knees bent. Loop a towel or strap around one foot and gently straighten that leg upward until you feel a comfortable stretch along the back of the thigh. Hold for about 20 to 30 seconds, then switch sides. Keep the opposite knee bent.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-gluteal-stretch.jpg" alt="Gluteal stretch exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Gluteal stretch</h3>
                <p>Lie on your back with knees bent. Cross one ankle over the opposite knee, then gently pull the lower thigh toward your chest until you feel a stretch in the buttock of the crossed leg. Hold for 20 to 30 seconds and switch sides.</p>
              </div>
            </li>
          </ul>

          <h2>Core and Spinal Mobility</h2>
          <ul class="exercise-grid">
            <li class="exercise-item">
              <img src="../images/ex-back-pelvic-tilt.jpg" alt="Pelvic tilt exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Pelvic tilt</h3>
                <p>Lie on your back with knees bent and feet flat. Gently flatten your lower back against the floor by tilting the top of your pelvis toward your ribs. Hold for a few seconds, then relax. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-partial-curl.jpg" alt="Partial curl exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Partial curl</h3>
                <p>Lie on your back with knees bent and arms folded across the chest. Gently lift your head and shoulders just a few inches off the floor, keeping the lower back in contact with the floor. Hold briefly, then lower. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-cat-camel.jpg" alt="Cat and camel exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Cat and camel</h3>
                <p>Start on hands and knees with a neutral spine. Slowly arch your back upward (rounding toward the ceiling) while letting your head drop slightly, then slowly let your back sag toward the floor while lifting your head slightly. Move smoothly between the two positions and repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-quadruped.jpg" alt="Quadruped arm and leg raise exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Quadruped arm and leg raise</h3>
                <p>Start on hands and knees with a neutral spine. Slowly extend one arm forward while extending the opposite leg straight back, keeping your back and pelvis level. Hold briefly, then return to the starting position. Switch sides and repeat several times on each side.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-extension.jpg" alt="Extension exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Extension exercise</h3>
                <p>Lie face down with your hands under your shoulders. Gently press up so your chest lifts a few inches off the floor while your pelvis stays in contact with the surface. Keep your back and neck relaxed. Hold briefly, then lower. Repeat several times.</p>
              </div>
            </li>
            <li class="exercise-item">
              <img src="../images/ex-back-side-planks.jpg" alt="Side plank exercise" width="480" height="360" loading="lazy" decoding="async">
              <div class="exercise-item-body">
                <h3>Side plank (beginner variation)</h3>
                <p>Lie on your side with knees bent and forearm on the floor under your shoulder. Lift your hips so your body forms a straight line from shoulders to knees. Hold for a short time, then lower. Repeat on both sides, gradually increasing the hold time as you get stronger.</p>
              </div>
            </li>
          </ul>

          <div class="callout-tip">
            <strong>Tip:</strong> Quality of movement matters more than how many repetitions you do. Stop a few reps short of fatigue, keep your breathing steady, and only progress to harder variations once a movement feels easy. Applying a light warm compress or taking a short walk before stretching can help reduce stiffness.
          </div>

          <div class="callout-warning">
            <strong>When to see a doctor:</strong> Stop the exercises and seek medical advice if you develop new or worsening back pain, pain that radiates down the leg below the knee, numbness, tingling, or weakness in the legs, loss of bladder or bowel control, fever, or pain after a fall or injury. These symptoms need evaluation before you continue any home program.
